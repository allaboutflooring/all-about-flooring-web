/**
 * Writes src/data/routeIndex.js — slim path/nav tables so the client
 * homepage bundle does not include every service and location page's SEO copy.
 *
 * Run from `npm run check` / `npm run build`. Source of truth stays in
 * services.js, areaPages.js and stpete.js.
 */
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SERVICE_PAGES } from '../src/data/services.js'
import { AREA_PAGES } from '../src/data/areaPages.js'
import {
  STPETE_BASE,
  STPETE_SERVICE_PAGES,
  STPETE_AREA_PAGES,
} from '../src/data/stpete.js'
import { ABOUT_PATH } from '../src/data/site.js'

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/routeIndex.js')

const serviceRoutes = Object.entries(SERVICE_PAGES).map(([slug, p]) => ({
  slug,
  path: p.path,
}))

const areaRoutes = Object.entries(AREA_PAGES).map(([slug, p]) => ({
  slug,
  path: p.path,
  skipRoute: Boolean(p.skipRoute),
}))

const stPeteServiceRoutes = Object.entries(STPETE_SERVICE_PAGES).map(([slug, p]) => ({
  slug,
  path: p.path,
}))

const stPeteAreaRoutes = Object.entries(STPETE_AREA_PAGES).map(([slug, p]) => ({
  slug,
  path: p.path,
}))

const navServices = Object.values(SERVICE_PAGES)
  .filter((p) => p.inNav)
  .map((p) => ({ href: p.path, label: p.navLabel || p.crumb }))

const navAreas = Object.values(AREA_PAGES).map((a) => ({
  href: a.path,
  label: a.city,
}))

const stPeteNavServices = Object.values(STPETE_SERVICE_PAGES)
  .filter((p) => p.inNav)
  .map((p) => ({ href: p.path, label: p.navLabel || p.crumb }))

const stPeteNavAreas = Object.values(STPETE_AREA_PAGES).map((a) => ({
  href: a.path,
  label: a.city,
}))

const areaHrefByCity = Object.fromEntries(
  Object.values(AREA_PAGES).map((a) => [a.city.toLowerCase(), a.path])
)

const stPeteAreaHrefByCity = Object.fromEntries(
  Object.values(STPETE_AREA_PAGES).map((a) => [a.city.toLowerCase(), a.path])
)

const json = (v) => JSON.stringify(v, null, 2)

const file = `/**
 * AUTO-GENERATED by scripts/write-route-index.mjs — do not edit by hand.
 * Slim route and nav tables. Full page copy lives in services.js / areaPages.js / stpete.js.
 */
export const STPETE_BASE = ${json(STPETE_BASE)}
export const ABOUT_PATH = ${json(ABOUT_PATH)}

export const SERVICE_ROUTES = ${json(serviceRoutes)}

export const AREA_ROUTES = ${json(areaRoutes)}

export const STPETE_SERVICE_ROUTES = ${json(stPeteServiceRoutes)}

export const STPETE_AREA_ROUTES = ${json(stPeteAreaRoutes)}

export const NAV_SERVICES = ${json(navServices)}

export const NAV_AREAS = ${json(navAreas)}

export const STPETE_NAV_SERVICES = ${json(stPeteNavServices)}

export const STPETE_NAV_AREAS = ${json(stPeteNavAreas)}

export const STPETE_NAV = [
  { href: STPETE_BASE, label: 'Home' },
  { href: \`\${STPETE_BASE}/services\`, label: 'Services', children: STPETE_NAV_SERVICES },
  { href: \`\${STPETE_BASE}/locations\`, label: 'Locations', children: STPETE_NAV_AREAS },
]

const AREA_HREF_BY_CITY = ${json(areaHrefByCity)}

const STPETE_AREA_HREF_BY_CITY = ${json(stPeteAreaHrefByCity)}

export const areaPageHref = (city) => AREA_HREF_BY_CITY[city.toLowerCase()] ?? null

export const stPeteAreaHref = (city) => STPETE_AREA_HREF_BY_CITY[city.toLowerCase()] ?? null
`

writeFileSync(out, file)
console.log(`[route-index] wrote ${out.replace(/.*\/src/, 'src')} (${file.length} bytes)`)
